// Draws the editor's graphics library: public/graphics/<id>.svg for every
// graphic, public/graphics/LICENSES.md, and the catalogue the app reads
// (src/lib/graphics-catalogue.gen.ts, and the bare ids in
// src/lib/graphics-ids.gen.ts). Run `pnpm graphics` after changing
// anything under scripts/graphics/.
//
// The art is drawn here from code, so it is original to this project and
// released CC0. logo-flv.svg is the Fashion Leader brand mark: it is listed
// in the catalogue but its file is never rewritten.
import { mkdirSync, writeFileSync } from 'node:fs'

import { svg } from './graphics/draw.mjs'
import { CROSSES } from './graphics/crosses.mjs'
import { FLAMES } from './graphics/flames.mjs'
import { FLORALS } from './graphics/florals.mjs'
import { ORNAMENTS } from './graphics/ornaments.mjs'
import { PATTERNS } from './graphics/patterns.mjs'
import { SHAPES } from './graphics/shapes.mjs'
import { SYMBOLS } from './graphics/symbols.mjs'

const root = new URL('../', import.meta.url)
const out = new URL('public/graphics/', root)
mkdirSync(out, { recursive: true })

// Match GRAPHIC_DEFAULT_AUTHOR and GRAPHIC_DEFAULT_LICENCE in src/lib/graphics-library.ts.
const AUTHOR = 'Fashion Leader Vote studio'
const LICENCE = 'CC0-1.0'

const BRAND = {
  id: 'logo-flv',
  label: 'FLV Mark',
  category: 'logos',
  tags: ['fashion leader', 'flv', 'brand', 'logo'],
  author: 'Fashion Leader Vote',
  licence: 'All rights reserved',
}

const drawn = [...FLAMES, ...CROSSES, ...SYMBOLS, ...PATTERNS, ...FLORALS, ...ORNAMENTS, ...SHAPES]
const ids = new Set()

for (const graphic of drawn) {
  if (ids.has(graphic.id) || graphic.id === BRAND.id) {
    throw new Error(`Duplicate graphic id ${graphic.id}`)
  }
  ids.add(graphic.id)
  const { body, defs } = graphic.draw()
  const text = svg({ width: graphic.width, height: graphic.height, body, defs })
  writeFileSync(new URL(`${graphic.id}.svg`, out), text)
}

const catalogue = [
  ...drawn.map(({ id, label, category, tags }) => ({ id, label, category, tags, author: AUTHOR, licence: LICENCE })),
  BRAND,
]

const rows = catalogue.map(({ id, label, category, tags, author, licence }) => {
  const extra = author === AUTHOR && licence === LICENCE ? '' : `, ${JSON.stringify(author)}, ${JSON.stringify(licence)}`
  return `  [${JSON.stringify(id)}, ${JSON.stringify(label)}, ${JSON.stringify(category)}, ${JSON.stringify(tags.join(' '))}${extra}],`
})

writeFileSync(
  new URL('src/lib/graphics-catalogue.gen.ts', root),
  `// Generated by scripts/build-graphics.mjs (pnpm graphics). Do not edit.
// Each row: id, label, category, space-separated tags, then author and
// licence when they differ from the studio default.
import type { GraphicRow } from './graphics-library.ts'

export const GRAPHIC_ROWS: readonly GraphicRow[] = [
${rows.join('\n')}
]
`,
)

// The ids alone, for code on the app's first load (library-assets.ts)
// that must know which graphics ship without pulling in the catalogue.
writeFileSync(
  new URL('src/lib/graphics-ids.gen.ts', root),
  `// Generated by scripts/build-graphics.mjs (pnpm graphics). Do not edit.
export const GRAPHIC_IDS: readonly string[] = ${JSON.stringify(catalogue.map(({ id }) => id))}
`,
)

const licenceRows = catalogue.map(
  ({ id, label, author, licence }) => `| \`${id}.svg\` | ${label} | ${author} | ${licence} | ${id === BRAND.id ? 'Brand mark, supplied' : 'Drawn in code, `scripts/build-graphics.mjs`'} |`,
)

writeFileSync(
  new URL('LICENSES.md', out),
  `# Graphics library licences

Every graphic here except \`logo-flv.svg\` was drawn for this project in code
by \`scripts/build-graphics.mjs\` (with the shapes in \`scripts/graphics/\`).
None is traced from, or based on, a third-party image. They are dedicated to
the public domain under CC0 1.0:
https://creativecommons.org/publicdomain/zero/1.0/

\`logo-flv.svg\` is the Fashion Leader Vote brand mark. It is not CC0 and is
not redrawn by the script.

This file is generated. To add a graphic, draw it under \`scripts/graphics/\`
and run \`pnpm graphics\`.

| File | Name | Author | Licence | Source |
| --- | --- | --- | --- | --- |
${licenceRows.join('\n')}
`,
)

console.log(`build-graphics: ${drawn.length} drawn, ${catalogue.length} in the catalogue`)
